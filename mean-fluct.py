# HISTOGRAMM DER FLUKTUATIONSVERTEILUNG
# ============================================================

def create_fluctuation_histogram(results):
    """
    Erzeugt ein echtes Histogramm der RMS-Fluktuationen.

    x-Achse:
        RMS-Fluktuation in nm

    y-Achse:
        Anzahl der Teilchen oder Wahrscheinlichkeitsdichte

    Bei mehreren XYZ-Dateien werden die Histogramme
    transparent übereinander dargestellt.
    """

    plt.figure(
        figsize=(10, 6)
    )

    for result in results:

        fluctuations = np.asarray(
            result["fluctuation"],
            dtype=float
        )

        # Ungültige Werte entfernen
        valid_fluctuations = fluctuations[
            np.isfinite(fluctuations)
        ]

        # Für logarithmische Achsen keine Werte <= 0 verwenden
        if USE_LOG_SCALE:
            valid_fluctuations = valid_fluctuations[
                valid_fluctuations > 0
            ]

        if len(valid_fluctuations) == 0:
            print(
                f"Warnung: Für {result['name']} sind keine "
                f"gültigen Fluktuationswerte vorhanden."
            )
            continue

        plt.hist(
            valid_fluctuations,
            bins=HISTOGRAM_BINS,
            alpha=0.55,
            edgecolor="black",
            density=NORMALIZE_HISTOGRAM,
            label=result["name"]
        )

    if USE_LOG_SCALE:
        plt.xscale("log")

    plt.xlabel("RMS-Fluktuation / nm")

    if NORMALIZE_HISTOGRAM:
        plt.ylabel("Wahrscheinlichkeitsdichte")
    else:
        plt.ylabel("Anzahl der Teilchen")

    plt.title(
        "Verteilung der RMS-Fluktuationen"
    )

    plt.grid(
        True,
        axis="y",
        alpha=0.3
    )

    plt.legend()
    plt.tight_layout()

    output_path = (
        OUTPUT_FOLDER
        / HISTOGRAM_FILENAME
    )

    plt.savefig(
        output_path,
        dpi=300,
        bbox_inches="tight"
    )

    print(
        f"Histogramm gespeichert:\n"
        f"{output_path.resolve()}"
    )

    plt.show()
    plt.close()


